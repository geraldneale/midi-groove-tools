#!/bin/sh
# install.sh: install MIDI Groove Tools commands on macOS or Linux.
#
#   From a clone:   ./install.sh
#   One line:       curl -fsSL https://raw.githubusercontent.com/geraldneale/midi-groove-tools/main/install.sh | sh
#   Update:         run either again
#   Uninstall:      ./install.sh --uninstall
#
# The command names are the stable interface. Today each command runs a Python
# module from a private venv. When a tool is rewritten in Rust, this script
# installs that binary under the same name instead; nothing else changes.

set -eu

REPO_URL="${MIDI_TOOLS_REPO:-https://github.com/geraldneale/midi-groove-tools.git}"
DATA_DIR="${MIDI_TOOLS_HOME:-$HOME/.local/share/midi-groove-tools}"
BIN_DIR="${MIDI_TOOLS_BIN:-$HOME/.local/bin}"
VENV="$DATA_DIR/venv"

# command name : python module
TOOLS="midi-watch:watch midi-watch-all:watch_all midi-forward:forward beatmap:beatmap midi-align:midi_align midi-clean:midi_clean midi-dump:midi_dump midi-monitor:midi_monitor song-minus-stems:song_minus_stems hits-to-midi:hits_to_midi midi-clock-check:clock_check midi-tools-test:test_midi_tools"

say() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

uninstall() {
    for entry in $TOOLS; do
        rm -f "$BIN_DIR/${entry%%:*}"
    done
    rm -rf "$DATA_DIR"
    say "midi-groove-tools removed."
    exit 0
}

[ "${1:-}" = "--uninstall" ] && uninstall

OS="$(uname -s)"
case "$OS" in
    Darwin|Linux) ;;
    *) die "unsupported OS: $OS (macOS and Linux only)" ;;
esac

# Find the source: this clone, or clone/update into DATA_DIR/src.
SCRIPT_DIR=""
case "$0" in
    */install.sh) SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)" ;;
esac
if [ -n "$SCRIPT_DIR" ] && [ -d "$SCRIPT_DIR/python/midi_tools" ]; then
    SRC="$SCRIPT_DIR"
elif ! command -v git >/dev/null 2>&1 || { [ "$OS" = "Darwin" ] && ! xcode-select -p >/dev/null 2>&1; }; then
    # No git, or a Mac without the Command Line Tools (its /usr/bin/git is only a stub
    # that pops up an installer): download the archive instead.
    SRC="$DATA_DIR/src"
    TARBALL="${MIDI_TOOLS_TARBALL:-https://github.com/geraldneale/midi-groove-tools/archive/refs/heads/main.tar.gz}"
    say "Downloading $TARBALL (git not available)"
    mkdir -p "$DATA_DIR"
    rm -rf "$SRC" "$DATA_DIR/src.new"
    mkdir -p "$DATA_DIR/src.new"
    curl -fsSL "$TARBALL" | tar xz -C "$DATA_DIR/src.new" --strip-components 1
    mv "$DATA_DIR/src.new" "$SRC"
else
    SRC="$DATA_DIR/src"
    if [ -d "$SRC/.git" ]; then
        say "Updating $SRC"
        git -C "$SRC" pull --ff-only
    else
        say "Cloning $REPO_URL"
        mkdir -p "$DATA_DIR"
        git clone --depth 1 "$REPO_URL" "$SRC"
    fi
fi

# Python 3.9+ with venv.
PY="$(command -v python3 || true)"
[ -n "$PY" ] || die "python3 not found"
"$PY" -c 'import sys; sys.exit(sys.version_info < (3, 9))' \
    || die "python 3.9 or newer is required"
"$PY" -c 'import venv, ensurepip' 2>/dev/null \
    || die "python venv support missing (Debian/Ubuntu: sudo apt install python3-venv)"

# Linux needs the ALSA runtime library for MIDI ports.
if [ "$OS" = "Linux" ] && ! ldconfig -p 2>/dev/null | grep -q 'libasound\.so\.2'; then
    say "warning: ALSA library not found. Install it first:"
    say "  Arch: sudo pacman -S alsa-lib    Debian/Ubuntu: sudo apt install libasound2"
fi

say "Setting up Python environment in $VENV"
mkdir -p "$DATA_DIR"
[ -x "$VENV/bin/python" ] || "$PY" -m venv "$VENV"
"$VENV/bin/python" -m pip install --quiet --upgrade pip
"$VENV/bin/python" -m pip install --quiet -r "$SRC/python/requirements.txt"

mkdir -p "$BIN_DIR"
for entry in $TOOLS; do
    name="${entry%%:*}"
    module="${entry##*:}"
    rust_bin="$SRC/rust/target/release/$name"
    if [ -x "$rust_bin" ]; then
        ln -sf "$rust_bin" "$BIN_DIR/$name"
        say "  $name (rust)"
    else
        cat > "$BIN_DIR/$name" <<EOF
#!/bin/sh
# generated by midi-groove-tools install.sh
PYTHONPATH="$SRC/python\${PYTHONPATH:+:\$PYTHONPATH}" exec "$VENV/bin/python" -m midi_tools.$module "\$@"
EOF
        chmod +x "$BIN_DIR/$name"
        say "  $name"
    fi
done

case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) say ""
       say "Add $BIN_DIR to your PATH, e.g. in ~/.zshrc or ~/.bashrc:"
       say "  export PATH=\"$BIN_DIR:\$PATH\"" ;;
esac

say ""
say "Done. Try: midi-watch"
